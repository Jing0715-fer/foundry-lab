// R1 — session-grant minting for the skill-events push channel.
//
// SERVER-ONLY (node:crypto + fs). Browsers never import this module: they
// ask GET /api/skills/events-session, which mints the grant server-side.
//
// A grant is the connection's ENTITLEMENT — the maximum room set that
// connection may ever subscribe to. The skill-events service verifies the
// HMAC-SHA256 signature and clamps every subscribe to the payload's rooms
// (voluntary subscriptions can only NARROW, never expand — the Q2
// eavesdropping hole closed server-side).
//
//   token = "v1.<expiryMs>.<payloadB64url>.<hmacB64url>"
//     payload = JSON { rooms: string[] }
//     hmac    = HMAC-SHA256(signingKey, "v1.<expiryMs>.<payloadB64url>")
//
// Secret source (mirrors the service exactly — env first, file fallback):
//   SKILL_EVENTS_SIGNING_KEY env  →  mini-services/skill-events/.signing-key
// The file is generated by the service at first boot (gitignored, 0600).
//
// Rotation story: minting re-reads the key on EVERY call (no TTL cache —
// mints are rare, one per browser session, and a file read is sub-ms; a
// cached key would mint grants the service just invalidated). The service
// re-reads its copy on the first failed verification. Rotating the key
// therefore self-heals without restarting either process: old grants fail
// the connect middleware → the browser hook re-mints (fresh key) →
// reconnects with a valid grant.

import { createHmac } from "crypto";
import { existsSync, readFileSync } from "fs";
import { resolve } from "path";

/** Default grant lifetime: 12h (a browser session outliving that reconnects,
 *  which re-mints — the hook handles connect_error exactly this way). */
export const GRANT_DEFAULT_TTL_MS = 12 * 60 * 60 * 1000;
/** Minimum accepted signing-key length (parity with the service's check). */
const KEY_MIN_LENGTH = 32;

const SIGNING_KEY_PATH = resolve(
  process.cwd(),
  "mini-services/skill-events/.signing-key",
);

function currentSigningKey(): string | null {
  const fromEnv = process.env.SKILL_EVENTS_SIGNING_KEY?.trim();
  if (fromEnv && fromEnv.length >= KEY_MIN_LENGTH) return fromEnv;
  try {
    if (existsSync(SIGNING_KEY_PATH)) {
      const key = readFileSync(SIGNING_KEY_PATH, "utf8").trim();
      if (key.length >= KEY_MIN_LENGTH) return key;
    }
  } catch {
    // Unreadable key file — the mint fails honestly (null) and the route
    // reports it; the browser falls back to polling. Never mint unsigned.
  }
  return null;
}

export interface SkillEventsSession {
  /** The opaque grant token — present in the socket.io handshake auth. */
  token: string;
  /** The entitlement rooms the grant carries (echo for logging/debugging). */
  rooms: string[];
  /** ISO timestamp when the grant stops being accepted by the service. */
  expiresAt: string;
}

/** Mint one signed session grant. `rooms` is the ENTITLEMENT (maximum room
 *  set) — the identity decision belongs to the CALLER (server-side), never
 *  to the browser. Throws when no signing key is available (service not
 *  booted yet / env misconfigured) — the route maps that to an honest 503
 *  and the browser keeps polling. */
export function mintSkillEventsSession(
  rooms: string[],
  ttlMs: number = GRANT_DEFAULT_TTL_MS,
): SkillEventsSession {
  const key = currentSigningKey();
  if (!key) {
    throw new Error(
      "skill-events signing key unavailable — start the skill-events " +
        "service (it generates .signing-key at boot) or set " +
        "SKILL_EVENTS_SIGNING_KEY",
    );
  }
  // Defensive normalization: the payload rides INSIDE the signed bytes, but
  // a malformed room would still confuse the service's clamp — normalize
  // exactly like the service parses (grammar + dedupe).
  const normalized = [...new Set(rooms)].filter(
    (r) =>
      typeof r === "string" &&
      /^(all|agent:[A-Za-z0-9_-]{1,64}|workflow:[A-Za-z0-9_-]{1,64})$/.test(r),
  );
  const expiresAtMs = Date.now() + Math.max(ttlMs, 60_000);
  const payload = JSON.stringify({ rooms: normalized });
  const payloadB64 = Buffer.from(payload, "utf8").toString("base64url");
  const expRaw = String(expiresAtMs);
  const sig = createHmac("sha256", key)
    .update(`v1.${expRaw}.${payloadB64}`)
    .digest("base64url");
  return {
    token: `v1.${expRaw}.${payloadB64}.${sig}`,
    rooms: normalized,
    expiresAt: new Date(expiresAtMs).toISOString(),
  };
}
