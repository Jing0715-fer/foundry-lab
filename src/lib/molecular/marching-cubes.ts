// marching-cubes.ts — 通用 Marching Cubes 等值面三角化（零依赖、纯 TypeScript）
//
// 用途：对规则三维标量场（如 CCP4/MRC 电子密度图）提取 iso 等值面的三角网格，
//       输出非索引网格（positions + normals），可直接送入 three.js BufferGeometry。
//
// 数据约定（与 ccp4.ts 的规范化输出一致）：
//   - data 长度 = nx*ny*nz，索引 = (k*ny + j)*nx + i（i 沿 x 最快，k 沿 z 最慢）；
//   - 输出 positions 为网格坐标（体素单位，各轴 0..n-1），调用方可结合 Ccp4Map
//     的 fracOrigin/fracStep 换算分数坐标，再经晶胞矩阵换算笛卡尔坐标（Å）。
//
// 算法：标准 Marching Cubes（Lorensen & Cline 1987），常量表取 Paul Bourke
//       公开发表的标准版本：256 项 edgeTable + 256×16 triTable
//       （http://paulbourke.net/geometry/polygonise/）。
//   - 角点 bit 约定：角值 < iso 记为「内」，cubeindex 汇集 8 个角点内/外位；
//   - 三角形顶点 = 棱上线性插值 p = p0 + (iso−v0)/(v1−v0)·(p1−p0)（p0 取
//     棱的低坐标端点，方向规范统一，见 EDGE_A/EDGE_B 处注释）；
//   - 法线 = −∇f（中心差分，边界单侧差分），棱两端角点法线用同一插值系数线性
//     插值后归一化（比逐面法线平滑）；角点法线仅对活跃单元格按需计算，零额外大数组；
//   - 输出采用可增长 Float32Array（2^16 floats 起步、倍增拷贝），达到 maxTriangles
//     （默认 500000）即停止并置 truncated = true；
//   - 热路径（单元格扫描/插值/写三角形）无任何对象分配，暂存全部为模块级复用数组。

/** Marching Cubes 输出结果 */
export interface McResult {
  positions: Float32Array // xyz × count（非索引网格：每个三角形独立 3 个顶点）
  normals: Float32Array   // 单位法线 xyz × count（= −∇f 插值后归一化）
  count: number           // 顶点数（= 三角形数 × 3）
  truncated: boolean      // 因达到 maxTriangles 而提前停止
}

