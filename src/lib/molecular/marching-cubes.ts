/**
 * Marching Cubes 自检（纯内存合成数据，无 IO）：
 *  1) 48³ 球密度场（场公式半径 R = 0.5N，值 = 100·(1−(d/R)²)，iso = 50
 *     → 等值面理论半径 = R·√0.5 ≈ 0.354N，落在 [0.3N, 0.4N] 区间中央）：
 *     顶点数 2000~60000、全部顶点距中心 ∈ [0.3N, 0.4N]（15% 容差）、
 *     法线单位化 |‖n‖−1| < 0.01、法线与径向夹角 < 30°（采样 200 个）、
 *     包围盒关于网格中心对称；
 *  2) maxTriangles 截断行为；
 *  3) 全内/全外空输出；
 *  4) 各向异性维度 8×6×5（验证 (k*ny+j)*nx+i 索引约定与轴不被混淆）；
 *  5) 网格封闭性（流形）检查：每条无向棱恰被 2 个三角形共享。
 * @returns ok 与 details（中文描述）
 */
export function mcSelfTest(): { ok: boolean; details: string } {
  const fails: string[] = []
  const info: string[] = []

  // ── 1) 球密度场 ──
  const N = 48
  const c = (N - 1) / 2          // 网格中心（0..N-1 的中点，保证完全对称）
  const R = 0.5 * N              // 场公式半径；iso=50 → 面半径 ≈ 0.354N
  const field = new Float32Array(N * N * N)
  for (let k = 0; k < N; k++) {
    const dz = k - c
    for (let j = 0; j < N; j++) {
      const dy = j - c
      const row = (k * N + j) * N
      for (let i = 0; i < N; i++) {
        const dx = i - c
        field[row + i] = 100 * (1 - (dx * dx + dy * dy + dz * dz) / (R * R))
      }
    }
  }
  const t0 = performance.now()
  const r = marchingCubes(field, N, N, N, 50)
  const dt = performance.now() - t0
  info.push(`球测试：顶点 ${r.count}（三角形 ${r.count / 3}，耗时 ${dt.toFixed(1)}ms）`)

  if (r.truncated) fails.push('球测试意外截断')
  if (r.count < 2000 || r.count > 60000) fails.push(`球测试顶点数 ${r.count} 超出 [2000, 60000]`)
  if (r.positions.length !== r.count * 3 || r.normals.length !== r.count * 3) {
    fails.push('球测试输出数组长度与 count 不一致')
  }

  // 顶点距离 ∈ [0.3N, 0.4N]（15% 容差）
  const lo = 0.3 * N * 0.85
  const hi = 0.4 * N * 1.15
  let dmin = Infinity
  let dmax = 0
  let badDist = 0
  for (let v = 0; v < r.count; v++) {
    const dx = r.positions[v * 3] - c
    const dy = r.positions[v * 3 + 1] - c
    const dz = r.positions[v * 3 + 2] - c
    const d = Math.sqrt(dx * dx + dy * dy + dz * dz)
    if (d < dmin) dmin = d
    if (d > dmax) dmax = d
    if (d < lo || d > hi) badDist++
  }
  if (badDist > 0) fails.push(`球测试 ${badDist} 个顶点距中心超出 [${lo.toFixed(1)}, ${hi.toFixed(1)}]`)
  info.push(`顶点距中心 [${dmin.toFixed(2)}, ${dmax.toFixed(2)}]（理论 ${(R * Math.SQRT1_2).toFixed(2)}）`)

  // 法线长度 |‖n‖−1| < 0.01（全部顶点）
  let badLen = 0
  for (let v = 0; v < r.count; v++) {
    const l = Math.hypot(r.normals[v * 3], r.normals[v * 3 + 1], r.normals[v * 3 + 2])
    if (Math.abs(l - 1) >= 0.01) badLen++
  }
  if (badLen > 0) fails.push(`球测试 ${badLen} 个法线长度偏离 1 超过 0.01`)

  // 法线方向 ≈ 径向外指：与位置向量夹角 < 30°（均匀采样 200 个顶点）
  const cosLimit = Math.cos((30 * Math.PI) / 180)
  const stride = Math.max(1, Math.floor(r.count / 200))
  let badDir = 0
  let sampled = 0
  for (let v = 0; v < r.count; v += stride) {
    sampled++
    const px = r.positions[v * 3] - c
    const py = r.positions[v * 3 + 1] - c
    const pz = r.positions[v * 3 + 2] - c
    const pl = Math.sqrt(px * px + py * py + pz * pz)
    if (pl === 0) continue
    const dot = (r.normals[v * 3] * px + r.normals[v * 3 + 1] * py + r.normals[v * 3 + 2] * pz) / pl
    if (dot < cosLimit) badDir++
  }
  if (badDir > 0) fails.push(`球测试 ${badDir}/${sampled} 个采样法线与径向夹角 ≥ 30°`)
  info.push(`法线径向检查 ${sampled - badDir}/${sampled} 通过`)

  // 包围盒关于中心对称
  const bbMin = [Infinity, Infinity, Infinity]
  const bbMax = [-Infinity, -Infinity, -Infinity]
  for (let v = 0; v < r.count; v++) {
    for (let ax = 0; ax < 3; ax++) {
      const val = r.positions[v * 3 + ax]
      if (val < bbMin[ax]) bbMin[ax] = val
      if (val > bbMax[ax]) bbMax[ax] = val
    }
  }
  let maxDev = 0
  for (let ax = 0; ax < 3; ax++) {
    const dev = Math.abs((bbMin[ax] + bbMax[ax]) / 2 - c)
    if (dev > maxDev) maxDev = dev
  }
  if (maxDev > 0.05) fails.push(`球测试包围盒不对称（中点偏差 ${maxDev.toFixed(3)}）`)
  info.push(`包围盒中点偏差 ${maxDev.toExponential(1)}`)

  // ── 2) 截断行为 ──
  const tc = marchingCubes(field, N, N, N, 50, 10)
  if (!tc.truncated || tc.count !== 30) {
    fails.push(`截断测试异常（truncated=${tc.truncated}, count=${tc.count}, 应为 30）`)
  }

  // ── 3) 全内 / 全外 ──
  const eo = marchingCubes(field, N, N, N, 1e6)
  const ei = marchingCubes(field, N, N, N, -1e6)
  if (eo.count !== 0 || ei.count !== 0 || eo.truncated || ei.truncated) {
    fails.push('空场测试失败（全内/全外应输出 0 顶点且不截断）')
  }

  // ── 4) 各向异性维度 8×6×5（验证索引约定）──
  const AX = 8
  const AY = 6
  const AZ = 5
  const px0 = 5
  const py0 = 3
  const pz0 = 2
  const af = new Float32Array(AX * AY * AZ)
  for (let k = 0; k < AZ; k++) {
    for (let j = 0; j < AY; j++) {
      for (let i = 0; i < AX; i++) {
        const dx = i - px0
        const dy = j - py0
        const dz = k - pz0
        af[(k * AY + j) * AX + i] = 10 - 2 * (dx * dx + dy * dy + dz * dz)
      }
    }
  }
  const a = marchingCubes(af, AX, AY, AZ, 5)
  if (a.count === 0) {
    fails.push('各向异性测试无输出')
  } else {
    let badA = 0
    const aMin = [Infinity, Infinity, Infinity]
    const aMax = [-Infinity, -Infinity, -Infinity]
    for (let v = 0; v < a.count; v++) {
      const dx = a.positions[v * 3] - px0
      const dy = a.positions[v * 3 + 1] - py0
      const dz = a.positions[v * 3 + 2] - pz0
      const d = Math.sqrt(dx * dx + dy * dy + dz * dz)
      if (d < 1.2 || d > 2.0) badA++ // 理论面半径 √2.5 ≈ 1.58
      for (let ax = 0; ax < 3; ax++) {
        const val = a.positions[v * 3 + ax]
        if (val < aMin[ax]) aMin[ax] = val
        if (val > aMax[ax]) aMax[ax] = val
      }
    }
    if (badA > 0) fails.push(`各向异性测试 ${badA} 个顶点距峰点超出 [1.2, 2.0]`)
    let badBox = false
    const want = [px0, py0, pz0]
    for (let ax = 0; ax < 3; ax++) {
      if (Math.abs((aMin[ax] + aMax[ax]) / 2 - want[ax]) > 0.25) badBox = true
    }
    if (badBox) fails.push('各向异性测试包围盒中心偏离峰点（轴序/索引疑似错误）')
    info.push(`各向异性测试：顶点 ${a.count}`)
  }

  // ── 5) 网格封闭性（流形）：每条无向棱恰被 2 个三角形共享 ──
  //   共享棱顶点由规范化插值方向保证位级一致，可直接按坐标字符串去重。
  const vid = new Map<string, number>()
  for (let v = 0; v < r.count; v++) {
    const key = `${r.positions[v * 3]},${r.positions[v * 3 + 1]},${r.positions[v * 3 + 2]}`
    if (!vid.has(key)) vid.set(key, vid.size)
  }
  const incid = new Map<string, number>()
  const triIds = new Int32Array(r.count)
  for (let v = 0; v < r.count; v++) {
    triIds[v] = vid.get(`${r.positions[v * 3]},${r.positions[v * 3 + 1]},${r.positions[v * 3 + 2]}`) ?? -1
  }
  for (let v = 0; v < r.count; v += 3) {
    const i0 = triIds[v]
    const i1 = triIds[v + 1]
    const i2 = triIds[v + 2]
    const pairs: Array<[number, number]> = [[i0, i1], [i1, i2], [i2, i0]]
    for (const [p, q] of pairs) {
      const key = p < q ? `${p}-${q}` : `${q}-${p}`
      incid.set(key, (incid.get(key) ?? 0) + 1)
    }
  }
  let openEdges = 0
  for (const n of incid.values()) {
    if (n !== 2) openEdges++
  }
  if (openEdges > 0) fails.push(`球测试网格不封闭（${openEdges} 条棱共享数 ≠ 2）`)
  info.push(`流形检查：${incid.size} 条棱共享数均为 2（顶点去重后 ${vid.size} 个）`)

  const details = [...info, fails.length > 0 ? `失败项：${fails.join('；')}` : '全部检查通过'].join('；')
  return { ok: fails.length === 0, details }
}
