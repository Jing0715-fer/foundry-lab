// 坐标与矩阵约定（与 PDB / CCP4 / sffourier.ts 完全一致）：
//   · SymOp 在分数坐标下作用：f' = R·f + t。R 为 3×3 行主序整数矩阵
//     （rot[i*3+j] = 第 i 行 j 列），t ∈ [0,1)³ 且全部落在 1/12 格点——
//     覆盖晶体学全部平移分量（1/2、1/3、1/4、1/6 及其组合）。
//   · orthoMatrix(cell) 采用 PDB 正交化约定：c ∥ z，a 落在 xz 平面（与 z 轴夹
//     角 β），b 取 y > 0 分支；o 的三列 = a/b/c 格矢，即 cart = O·frac；
//     oi 为逆矩阵，frac = Oi·cart。
//   · mateTransforms 输出笛卡尔空间（Å）刚体变换 p' = R_cart·p + t_cart：
//     R_cart = O·R_f·O⁻¹，t_cart = O·(t_f + n)（n 为整数格矢平移）。
//
// 空间群操作表：全部 65 个 Sohncke（手性）空间群（仅含正当操作，det = +1），
// 数据取自国际晶体学表 A 卷（经 gemmi 0.7.5 / sgtbx 权威数据导出），逐群完成
// 机器校验：det=+1、平移∈1/12 格点、居心复合==完整群、乘法闭包、一般位置数。
// 表共 88 个归一化键：除 65 个群类型外，另含 PDB 常见单斜备择设置（P 1 21 1、
// C 1 2 1、A 1 2 1、I 1 2 1、P 1 1 21 …）与 R 群 :H（六方轴，缺省）/ :R（菱方
// 原始格）双设置。原则：不确定的冷门群宁可省略，绝不编造。
// ============================================================================

// ---------- 公共类型 ----------

/** 分数坐标空间群操作：f' = R·f + t（行主序 3×3 旋转 + 平移∈[0,1)³） */
export interface SymOp {
  rot: number[]
  trans: [number, number, number]
}

/** 晶胞参数（长度 Å，角度度） */
export interface CrystalCell {
  a: number
  b: number
  c: number
  alpha: number
  beta: number
  gamma: number
}

/** CRYST1 记录解析结果：晶胞 + 空间群符号（保留内部空格，如 "P 21 21 21"） */
export interface CrystalInfo extends CrystalCell {
  spaceGroup: string
}

/** 笛卡尔空间（Å）刚体变换（对称配偶）：p' = R·p + t，R 行主序 3×3 */
export interface MateTransform {
  rot: number[]
  trans: [number, number, number]
}

