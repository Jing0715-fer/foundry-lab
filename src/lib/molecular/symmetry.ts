/** 晶格居心平移（1/12 单位）：键首字母 → 平移集合（恒含 (0,0,0)）。
 *  R 缺省按六方轴 obverse 设置：+(2/3,1/3,1/3)+(1/3,2/3,2/3)；
 *  显式 ":R" 后缀 = 菱方原始格（无居心）。与 sffourier.ts 的
 *  centeringTranslations() 逐值一致（对已含居心的调用方复合幂等）。 */
const CENTERING_12: Record<string, number[][]> = {
  P: [[0, 0, 0]],
  A: [[0, 0, 0], [0, 6, 6]],
  B: [[0, 0, 0], [6, 0, 6]],
  C: [[0, 0, 0], [6, 6, 0]],
  I: [[0, 0, 0], [6, 6, 6]],
  F: [[0, 0, 0], [0, 6, 6], [6, 0, 6], [6, 6, 0]],
  R: [[0, 0, 0], [8, 4, 4], [4, 8, 8]], // 2/3,1/3,1/3 与 1/3,2/3,2/3
}

const NO_CENTERING: number[][] = [[0, 0, 0]]

// ---------- 符号归一化 ----------

/** Unicode 下标数字 → 普通数字（防御 "P 2₁ 2₁ 2₁" 之类写法） */
const SUBSCRIPT_DIGITS: Record<string, string> = {
  '\u2080': '0', '\u2081': '1', '\u2082': '2', '\u2083': '3', '\u2084': '4',
  '\u2085': '5', '\u2086': '6', '\u2087': '7', '\u2088': '8', '\u2089': '9',
}

/** H-M 符号归一化：大写 + 剔除空格/下划线/杂项字符（仅保留 A-Z 0-9 ':'）。
 *  "P 21 21 21" → "P212121"；"R 3:R" → "R3:R"；"p212121" → "P212121"。 */
function normalizeKey(symbol: string): string {
  if (typeof symbol !== 'string') return ''
  const upper = symbol.toUpperCase().replace(/[\u2080-\u2089]/g, (ch) => SUBSCRIPT_DIGITS[ch] ?? '')
  return upper.replace(/[^A-Z0-9:]/g, '')
}

/** 归一化键 → 居心平移集合（1/12 单位） */
function centeringForKey(key: string): number[][] {
  if (key.includes(':R')) return NO_CENTERING
  const c = CENTERING_12[key.charAt(0)]
  return c !== undefined ? c : NO_CENTERING
}

// ---------- 矩阵小工具（行主序 3×3） ----------

/** 3×3 矩阵乘积（行主序） */
function mul3(a: readonly number[], b: readonly number[]): number[] {
  return [
    a[0] * b[0] + a[1] * b[3] + a[2] * b[6], a[0] * b[1] + a[1] * b[4] + a[2] * b[7], a[0] * b[2] + a[1] * b[5] + a[2] * b[8],
    a[3] * b[0] + a[4] * b[3] + a[5] * b[6], a[3] * b[1] + a[4] * b[4] + a[5] * b[7], a[3] * b[2] + a[4] * b[5] + a[5] * b[8],
    a[6] * b[0] + a[7] * b[3] + a[8] * b[6], a[6] * b[1] + a[7] * b[4] + a[8] * b[7], a[6] * b[2] + a[7] * b[5] + a[8] * b[8],
  ]
}

/** 3×3 行列式 */
function det3(m: readonly number[]): number {
  return m[0] * (m[4] * m[8] - m[5] * m[7])
    - m[1] * (m[3] * m[8] - m[5] * m[6])
    + m[2] * (m[3] * m[7] - m[4] * m[6])
}

/** 平移 mod 1 回卷到 [0,1)，端点吸附到 0（容差 1e-9，防浮点尾差） */
function wrap01(x: number): number {
  const w = x - Math.floor(x)
  return w < 1e-9 || w > 1 - 1e-9 ? 0 : w
}

// ---------- 空间群操作查询 ----------

/** 空间群符号 → 完整对称操作列表（原始格 op × 居心平移，平移 mod 1 并去重）。
 *  未知 / 未收录符号返回 null（调用方自行降级；sffourier 对 null 退化为仅
 *  恒等 op）。输出 op 顺序：原始格 op 优先、居心平移次之（恒等 op 必在首位）。
 *  与 sffourier.buildFullOps() 的「居心再复合」幂等：本函数已含居心平移。 */
export function symOpsFor(symbol: string): SymOp[] | null {
  const key = normalizeKey(symbol)
  const prim = SOHNCKE_OPS[key]
  if (prim === undefined) return null
  const cent = centeringForKey(key)
  const seen = new Set<string>()
  const out: SymOp[] = []
  for (let i = 0; i < prim.length; i++) {
    const op = prim[i] // 12 整数：rot9 + t3（1/12 单位，均 ∈ [0,12)）
    for (let j = 0; j < cent.length; j++) {
      const c = cent[j]
      // 表平移与居心平移均非负且 < 12，其和 < 24，一次取模即回卷到 [0,12)
      const tx = (op[9] + c[0]) % 12
      const ty = (op[10] + c[1]) % 12
      const tz = (op[11] + c[2]) % 12
      const fp = op[0] + ',' + op[1] + ',' + op[2] + ',' + op[3] + ',' + op[4] + ','
        + op[5] + ',' + op[6] + ',' + op[7] + ',' + op[8] + '|' + tx + ',' + ty + ',' + tz
      if (seen.has(fp)) continue
      seen.add(fp)
      out.push({
        rot: [op[0], op[1], op[2], op[3], op[4], op[5], op[6], op[7], op[8]],
        trans: [tx / 12, ty / 12, tz / 12],
      })
    }
  }
  return out
}

/** 空间群符号 → { ops }（完整操作数，即一般位置多重性）；未知符号返回 null */
export function spaceGroupInfo(symbol: string): { ops: number } | null {
  const ops = symOpsFor(symbol)
  return ops === null ? null : { ops: ops.length }
}

