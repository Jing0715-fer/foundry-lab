/** PDB 正交化矩阵对：o（列 = a/b/c 格矢，cart = O·frac）与 oi（逆，frac = Oi·cart）。
 *  约定：c_vec = (0,0,c)；a_vec = (a·sinβ, 0, a·cosβ)；
 *        b_vec = (b·x, b·y, b·cosα)，x = (cosγ − cosα·cosβ)/sinβ，
 *        y = √(1 − x² − cos²α) 取正根。
 *  数值稳定：sinβ 下限钳制防 0 除；1 − x² − cos²α 的负舍入截 0；
 *  行列式退化（非法晶胞 / NaN）时返回单位阵（调用方应先行校验）。 */
export function orthoMatrix(cell: CrystalCell): { o: number[]; oi: number[] } {
  const rad = Math.PI / 180
  const a = cell.a, b = cell.b, c = cell.c
  // 角度恰好 90° 时余弦为 ~1e-17 的浮点噪声——吸附为精确 0（正交晶胞得到
  // 严格对角阵；真实非 90° 角（|cos| ≳ 1e-7）不受影响）
  const cosd = (deg: number): number => {
    const v = Math.cos(deg * rad)
    return Math.abs(v) < 1e-15 ? 0 : v
  }
  const ca = cosd(cell.alpha)
  const cb = cosd(cell.beta)
  const cg = cosd(cell.gamma)
  // 合法晶胞 β∈(0,180) ⇒ sinβ > 0；仅对退化输入防 0 除
  const sb = Math.max(Math.sin(cell.beta * rad), 1e-9)
  const x = (cg - ca * cb) / sb
  const y2 = 1 - x * x - ca * ca
  const y = Math.sqrt(y2 > 0 ? y2 : 0)
  const o = [
    a * sb, b * x, 0,
    0, b * y, 0,
    a * cb, b * ca, c,
  ]
  // 解析逆 = 伴随矩阵 / 行列式；det = a·b·c·sinβ·y = 晶胞体积
  const det = o[0] * (o[4] * o[8] - o[5] * o[7])
    - o[1] * (o[3] * o[8] - o[5] * o[6])
    + o[2] * (o[3] * o[7] - o[4] * o[6])
  if (!Number.isFinite(det) || Math.abs(det) < 1e-12) {
    return { o: [1, 0, 0, 0, 1, 0, 0, 0, 1], oi: [1, 0, 0, 0, 1, 0, 0, 0, 1] }
  }
  const oi = [
    (o[4] * o[8] - o[5] * o[7]) / det, (o[2] * o[7] - o[1] * o[8]) / det, (o[1] * o[5] - o[2] * o[4]) / det,
    (o[5] * o[6] - o[3] * o[8]) / det, (o[0] * o[8] - o[2] * o[6]) / det, (o[2] * o[3] - o[0] * o[5]) / det,
    (o[3] * o[7] - o[4] * o[6]) / det, (o[1] * o[6] - o[0] * o[7]) / det, (o[0] * o[4] - o[1] * o[3]) / det,
  ]
  return { o, oi }
}

// ---------- CRYST1 解析 ----------

/** 解析 PDB CRYST1 记录 → CrystalInfo；非 CRYST1 行或字段非法返回 null。
 *  固定列位（PDB v3.3）：a 7-15、b 16-24、c 25-33、α 34-40、β 41-47、
 *  γ 48-54、空间群 55-66、Z 67-70（Z 不入 CrystalInfo，仅占位）。
 *  列位解析失败（非定长等异常行）时退化为空白分隔 token 解析。 */
export function parseCryst1(line: string): CrystalInfo | null {
  if (typeof line !== 'string' || !line.startsWith('CRYST1')) return null
  const num = (s: string): number => {
    const v = parseFloat(s)
    return Number.isFinite(v) ? v : NaN
  }
  let a = num(line.substring(6, 15))
  let b = num(line.substring(15, 24))
  let c = num(line.substring(24, 33))
  let alpha = num(line.substring(33, 40))
  let beta = num(line.substring(40, 47))
  let gamma = num(line.substring(47, 54))
  let sg = line.substring(54, 66).trim()
  if (Number.isNaN(a) || Number.isNaN(b) || Number.isNaN(c)
    || Number.isNaN(alpha) || Number.isNaN(beta) || Number.isNaN(gamma)) {
    // 容错：非定长行按空白拆分重试（token：CRYST1 a b c α β γ [sg...]）
    const tk = line.trim().split(/\s+/)
    if (tk.length >= 7) {
      a = num(tk[1]); b = num(tk[2]); c = num(tk[3])
      alpha = num(tk[4]); beta = num(tk[5]); gamma = num(tk[6])
      sg = tk.slice(7).join(' ').trim()
    }
  }
  if (!(a > 0) || !(b > 0) || !(c > 0)) return null
  if (!(alpha > 0 && alpha < 180) || !(beta > 0 && beta < 180) || !(gamma > 0 && gamma < 180)) return null
  return { a, b, c, alpha, beta, gamma, spaceGroup: sg }
}

// ---------- 对称配偶（晶体 packing）变换 ----------

/** 判定 op 是否恒等（旋转 = I 且平移 ≈ 0 mod 1） */
function isIdentityOp(op: SymOp): boolean {
  const r = op.rot
  return r[0] === 1 && r[1] === 0 && r[2] === 0
    && r[3] === 0 && r[4] === 1 && r[5] === 0
    && r[6] === 0 && r[7] === 0 && r[8] === 1
    && Math.abs(op.trans[0]) < 1e-9 && Math.abs(op.trans[1]) < 1e-9 && Math.abs(op.trans[2]) < 1e-9
}

/** 两个候选变换在 1e-3 容差内是否相同（12 个分量逐一比较） */
function sameTransform(rot: readonly number[], t: readonly number[], cand: MateTransform): boolean {
  for (let i = 0; i < 9; i++) if (Math.abs(cand.rot[i] - rot[i]) > 1e-3) return false
  for (let i = 0; i < 3; i++) if (Math.abs(cand.trans[i] - t[i]) > 1e-3) return false
  return true
}

/** 生成「对称配偶」笛卡尔变换列表（晶体 packing / crystal contacts 用）。
 *  · 仅遍历非恒等 op（恒等 op + n=0 即原始分子自身；居心型恒等旋转 op
 *    如 (I, 1/2,1/2,0) 属非恒等，正常参与）——P1 等仅含恒等 op 的群返回 []。
 *  · 对每个 op 枚举格矢平移 n ∈ [−span,span]³，
 *    span = clamp(ceil((radius+bboxRadius)/min(a,b,c)) + 1, 1, 2)。
 *  · 收录条件：|R_cart·center + t_cart − center| ≤ radius + bboxRadius
 *    （配偶包围球中心到原分子中心的距离）。
 *  · 1e-3 容差去重；按距离升序；上限 400 条；未知群 / 非法参数返回 []。 */
export function mateTransforms(
  cell: CrystalCell,
  symbol: string,
  centerCart: readonly [number, number, number],
  radiusCart: number,
  bboxRadius: number,
): MateTransform[] {
  const ops = symOpsFor(symbol)
  if (ops === null || ops.length === 0) return []
  if (!(cell.a > 0) || !(cell.b > 0) || !(cell.c > 0)) return []
  const reach = radiusCart + bboxRadius
  if (!Number.isFinite(reach) || reach < 0) return []
  const cx = centerCart[0], cy = centerCart[1], cz = centerCart[2]
  if (!Number.isFinite(cx) || !Number.isFinite(cy) || !Number.isFinite(cz)) return []
  const { o, oi } = orthoMatrix(cell)
  const minABC = Math.min(cell.a, cell.b, cell.c)
  const span = Math.min(2, Math.max(1, Math.ceil(reach / minABC) + 1))
  const acc: { rot: number[]; trans: [number, number, number]; d: number }[] = []
  for (let oi2 = 0; oi2 < ops.length; oi2++) {
    const op = ops[oi2]
    if (isIdentityOp(op)) continue
    // 笛卡尔旋转 = O·R_f·O⁻¹（正交晶胞下退化为同一旋转）
    const rc = mul3(o, mul3(op.rot, oi))
    for (let nz = -span; nz <= span; nz++) {
      for (let ny = -span; ny <= span; ny++) {
        for (let nx = -span; nx <= span; nx++) {
          // 笛卡尔平移 = O·(t_f + n)
          const fx = op.trans[0] + nx
          const fy = op.trans[1] + ny
          const fz = op.trans[2] + nz
          const tx = o[0] * fx + o[1] * fy + o[2] * fz
          const ty = o[3] * fx + o[4] * fy + o[5] * fz
          const tz = o[6] * fx + o[7] * fy + o[8] * fz
          // 收录条件：变换后分子中心距原中心 ≤ radius + bboxRadius
          const dx = rc[0] * cx + rc[1] * cy + rc[2] * cz + tx - cx
          const dy = rc[3] * cx + rc[4] * cy + rc[5] * cz + ty - cy
          const dz = rc[6] * cx + rc[7] * cy + rc[8] * cz + tz - cz
          const d = Math.sqrt(dx * dx + dy * dy + dz * dz)
          if (d > reach + 1e-9) continue
          // 1e-3 去重（重复仅可能来自等价 op 组合，如高对称 + 特殊平移）
          let dup = false
          for (let k = 0; k < acc.length; k++) {
            if (sameTransform(rc, [tx, ty, tz], acc[k])) { dup = true; break }
          }
          if (dup) continue
          acc.push({ rot: rc, trans: [tx, ty, tz], d })
        }
      }
    }
  }
  // 距离升序 + 上限 400（先去重收集、后排序截断，保证保留最近的 400 个）
  acc.sort((p, q) => p.d - q.d)
  const out: MateTransform[] = []
  for (let i = 0; i < acc.length && i < 400; i++) {
    out.push({ rot: acc[i].rot, trans: acc[i].trans })
  }
  return out
}

// ---------- 自检 ----------

/** op 内容指纹（旋转精确拼接 + 平移吸附到 1/12 格点），用于去重 / 闭包校验 */
function opFingerprint(op: SymOp): string {
  return op.rot.join(',') + '|'
    + (Math.round(wrap01(op.trans[0]) * 12) % 12) + ','
    + (Math.round(wrap01(op.trans[1]) * 12) % 12) + ','
    + (Math.round(wrap01(op.trans[2]) * 12) % 12)
}

/** op 复合 a∘b：f'' = a·(b·f)，平移 mod 1 回卷 */
function composeOp(a: SymOp, b: SymOp): SymOp {
  const r = mul3(a.rot, b.rot)
  return {
    rot: r,
    trans: [
      wrap01(a.rot[0] * b.trans[0] + a.rot[1] * b.trans[1] + a.rot[2] * b.trans[2] + a.trans[0]),
      wrap01(a.rot[3] * b.trans[0] + a.rot[4] * b.trans[1] + a.rot[5] * b.trans[2] + a.trans[1]),
      wrap01(a.rot[6] * b.trans[0] + a.rot[7] * b.trans[1] + a.rot[8] * b.trans[2] + a.trans[2]),
    ],
  }
}

/** max |a·b − I|（3×3，用于正交化往返自检） */
function matMulMaxDiff(a: readonly number[], b: readonly number[]): number {
  let worst = 0
  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
      let s = 0
      for (let k = 0; k < 3; k++) s += a[i * 3 + k] * b[k * 3 + j]
      const diff = Math.abs(s - (i === j ? 1 : 0))
      if (diff > worst) worst = diff
    }
  }
  return worst
}

/** 模块自检（无外部依赖、无网络）：
 *  ① 全表 88 键 / 65 群：det=+1(1e-9)、平移∈[0,1)、无重复、含恒等、乘法闭包；
 *     操作数抽查（一般位置多重性）与符号归一化；
 *  ② orthoMatrix：正交晶胞 O=diag(a,b,c)；三斜晶胞 O·Oi≈I、Oi·O≈I、
 *     |det O| ≈ 解析晶胞体积；
 *  ③ crambbin 晶胞 P 21 21 21 对称配偶：0 < n < 60、全部中心距 ≤ 42；
 *  ④ parseCryst1 标准行字段 + 非法输入返回 null。 */
export function symmetrySelfTest(): { ok: boolean; details: string } {
  const lines: string[] = []
  let ok = true
  const check = (name: string, pass: boolean, info: string): void => {
    if (!pass) ok = false
    lines.push((pass ? '[通过] ' : '[失败] ') + name + (info ? ' — ' + info : ''))
  }

  // ① 操作表完整性（det / 平移范围 / 去重 / 恒等 / 闭包）
  {
    const keys = Object.keys(SOHNCKE_OPS)
    let badDet = 0, badRange = 0, dup = 0, noIdentity = 0, notClosed = 0
    for (const key of keys) {
      const ops = symOpsFor(key)
      if (ops === null) { notClosed++; continue }
      const seen = new Set<string>()
      let hasIdentity = false
      for (const op of ops) {
        if (Math.abs(det3(op.rot) - 1) > 1e-9) badDet++
        if (op.trans[0] < -1e-12 || op.trans[0] >= 1 || op.trans[1] < -1e-12
          || op.trans[1] >= 1 || op.trans[2] < -1e-12 || op.trans[2] >= 1) badRange++
        if (isIdentityOp(op)) hasIdentity = true
        const fp = opFingerprint(op)
        if (seen.has(fp)) dup++
        seen.add(fp)
      }
      if (!hasIdentity) noIdentity++
      // 乘法闭包：任意 a∘b（平移 mod 1）仍是群内 op
      for (let i = 0; i < ops.length; i++) {
        for (let j = 0; j < ops.length; j++) {
          if (!seen.has(opFingerprint(composeOp(ops[i], ops[j])))) { notClosed++; break }
        }
      }
    }
    check('Sohncke 操作表完整性',
      badDet === 0 && badRange === 0 && dup === 0 && noIdentity === 0 && notClosed === 0,
      `${keys.length} 键 / 65 群类型：det=+1、平移∈[0,1)、无重复、含恒等、乘法闭包全部通过`)
  }

  // ①b 操作数抽查（一般位置多重性；P6122=12：#178 点群 622 阶 12，螺旋不改变多重性）
  {
    const expect: Record<string, number> = {
      P1: 1, P21: 2, P212121: 4, C2: 4, P43212: 8, P6122: 12, R3: 9,
      F222: 16, I422: 16, R32: 18, F432: 96, I4132: 48, P213: 12, I23: 24,
    }
    const parts: string[] = []
    let cntOk = true
    for (const k of Object.keys(expect)) {
      const n = symOpsFor(k)?.length ?? -1
      if (n !== expect[k]) cntOk = false
      parts.push(k + '=' + n)
    }
    check('操作数抽查（一般位置多重性）', cntOk, parts.join(' '))
  }

  // ①c 符号归一化与未知群
  {
    const n1 = symOpsFor('P 21 21 21')?.length ?? -1
    const n2 = symOpsFor('p212121')?.length ?? -1
    const n3 = symOpsFor('P2_1 2_1 2_1')?.length ?? -1
    const info = spaceGroupInfo('P 21 21 21')
    const unknown = symOpsFor('XYZ 99') === null && symOpsFor('') === null && spaceGroupInfo('ABC') === null
    check('符号归一化',
      n1 === 4 && n2 === 4 && n3 === 4 && unknown && info !== null && info.ops === 4,
      `"P 21 21 21"/"p212121"/"P2_1 2_1 2_1" → 同一 4 op；spaceGroupInfo().ops=4；未知群 → null`)
  }

  // ② orthoMatrix：正交晶胞对角 + 三斜往返 + 体积
  {
    const cellO: CrystalCell = { a: 40.995, b: 18.651, c: 22.512, alpha: 90, beta: 90, gamma: 90 }
    const om1 = orthoMatrix(cellO)
    const diagOk = Math.abs(om1.o[0] - 40.995) < 1e-9 && Math.abs(om1.o[4] - 18.651) < 1e-9
      && Math.abs(om1.o[8] - 22.512) < 1e-9 && Math.abs(om1.o[1]) < 1e-12 && Math.abs(om1.o[2]) < 1e-12
      && Math.abs(om1.o[3]) < 1e-12 && Math.abs(om1.o[5]) < 1e-12 && Math.abs(om1.o[6]) < 1e-12
      && Math.abs(om1.o[7]) < 1e-12
    const cellT: CrystalCell = { a: 5.1, b: 6.2, c: 7.3, alpha: 80, beta: 75, gamma: 110 }
    const om2 = orthoMatrix(cellT)
    const rt1 = matMulMaxDiff(om2.o, om2.oi)
    const rt2 = matMulMaxDiff(om2.oi, om2.o)
    const rad = Math.PI / 180
    const ca = Math.cos(80 * rad), cb = Math.cos(75 * rad), cg = Math.cos(110 * rad)
    const vol = 5.1 * 6.2 * 7.3 * Math.sqrt(1 - ca * ca - cb * cb - cg * cg + 2 * ca * cb * cg)
    const detGot = det3(om2.o)
    const volOk = Math.abs(detGot - vol) <= 1e-9 * vol
    check('orthoMatrix 正交化',
      diagOk && rt1 < 1e-9 && rt2 < 1e-9 && volOk,
      `正交晶胞 O=diag(a,b,c)；三斜晶胞 O·Oi 最大偏差 ${Math.max(rt1, rt2).toExponential(2)}（阈值 1e-9），`
      + `|det O|=${detGot.toFixed(4)} ≈ 解析体积 ${vol.toFixed(4)}`)
  }

  // ③ crambin 晶胞对称配偶（P 21 21 21，41×18.65×22.5 Å）
  {
    const cell: CrystalCell = { a: 40.995, b: 18.651, c: 22.512, alpha: 90, beta: 90, gamma: 90 }
    const center: readonly [number, number, number] = [20, 9, 11]
    const mates = mateTransforms(cell, 'P 21 21 21', center, 30, 12)
    let maxD = 0
    for (const m of mates) {
      const dx = m.rot[0] * center[0] + m.rot[1] * center[1] + m.rot[2] * center[2] + m.trans[0] - center[0]
      const dy = m.rot[3] * center[0] + m.rot[4] * center[1] + m.rot[5] * center[2] + m.trans[1] - center[1]
      const dz = m.rot[6] * center[0] + m.rot[7] * center[1] + m.rot[8] * center[2] + m.trans[2] - center[2]
      const d = Math.sqrt(dx * dx + dy * dy + dz * dz)
      if (d > maxD) maxD = d
    }
    check('crambin 对称配偶',
      mates.length > 0 && mates.length < 60 && maxD <= 42 + 1e-6,
      `${mates.length} 个配偶（要求 0<n<60），最远配偶中心距 ${maxD.toFixed(2)} Å（≤ 42）`)
  }

  // ④ parseCryst1
  {
    const info = parseCryst1('CRYST1   64.500   62.503   69.875  90.00  90.00  90.00 P 21 21 21     4')
    const fields = info !== null && info.a === 64.5 && info.b === 62.503 && info.c === 69.875
      && info.alpha === 90 && info.beta === 90 && info.gamma === 90 && info.spaceGroup === 'P 21 21 21'
    const neg = parseCryst1('ATOM      1  N   ALA A   1       1.000   2.000   3.000  1.00 10.00           N') === null
      && parseCryst1('CRYST1  ab 1.0 2.0 3.0 90 90 90 P 1') === null
    check('parseCryst1 字段解析', fields && neg,
      fields && info !== null
        ? `a=${info.a} b=${info.b} c=${info.c} α=β=γ=90 sg="${info.spaceGroup}"；非 CRYST1 / 非法字段 → null`
        : '字段不符')
  }

  return { ok, details: lines.join('\n') }
}
